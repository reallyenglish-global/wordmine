import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
const root = join(process.cwd(),'contracts/pack-v0/fixtures/synthetic');
const files: Record<string,string|number[]> = {};
for (const file of readdirSync(root,{recursive:true,withFileTypes:true}).filter(f => f.isFile()).sort((a,b) => join(a.parentPath,a.name).localeCompare(join(b.parentPath,b.name),'en'))) {
  const full = join(file.parentPath,file.name); const name = relative(root,full).split(sep).join('/');
  files[name] = name.endsWith('.json') ? readFileSync(full,'utf8') : Array.from(readFileSync(full));
}
const target = 'src/package/synthetic.generated.ts';
const publicRoot = 'public/sample-pack';
const output = '// Generated by scripts/bundle-package.ts from original synthetic fixtures. Do not edit.\nexport const syntheticFiles: Record<string,string|number[]> = '+JSON.stringify(files,null,2)+';\n';
if (process.argv.includes('--check')) {
  if (readFileSync(target,'utf8') !== output) throw new Error('Synthetic bundle drift; run npx tsx scripts/bundle-package.ts');
  if (!existsSync(publicRoot)) throw new Error('Web sample package missing; run npx tsx scripts/bundle-package.ts');
  const actual = readdirSync(publicRoot,{recursive:true,withFileTypes:true}).filter(f => f.isFile())
    .map(f => relative(publicRoot,join(f.parentPath,f.name)).split(sep).join('/')).sort();
  if (JSON.stringify(actual) !== JSON.stringify(Object.keys(files).sort())) throw new Error('Web sample package file-list drift; run npx tsx scripts/bundle-package.ts');
  for (const [name,value] of Object.entries(files)) {
    const expected = Buffer.from(value);
    if (!readFileSync(join(publicRoot,name)).equals(expected)) throw new Error(`Web sample package drift at ${name}; run npx tsx scripts/bundle-package.ts`);
  }
} else {
  writeFileSync(target,output);
  rmSync(publicRoot,{recursive:true,force:true}); mkdirSync(publicRoot,{recursive:true});
  for (const [name,value] of Object.entries(files)) {
    const destination = join(publicRoot,name); mkdirSync(dirname(destination),{recursive:true});
    writeFileSync(destination,typeof value === 'string' ? value : Uint8Array.from(value));
  }
}
console.log(`Synthetic bundle and web download fixture: ${Object.keys(files).length} files`);
