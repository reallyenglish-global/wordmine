import {readFileSync, writeFileSync} from 'node:fs';
import Ajv from 'ajv/dist/2020';
import standaloneCode from 'ajv/dist/standalone';
import schema from '../contracts/pack-v0/package.schema.json';

// Code generation is intentionally build-time only. Runtime imports the static output.
const ajv = new Ajv({strict:true,allErrors:false,code:{source:true,esm:true,optimize:true}});
ajv.addSchema(schema);
const references = Object.fromEntries(['manifest','lists','words','questions','answers'].map(role =>
  [role,`${schema.$id}#/$defs/${role}`]));
const output = '// @ts-nocheck\n// Generated by scripts/generate-package-validators.ts. Do not edit.\n'+standaloneCode(ajv,references)+'\n';
const path = 'src/package/validators.generated.ts';
if (process.argv.includes('--check')) {
  if (readFileSync(path,'utf8') !== output) throw new Error('Package validators drift; regenerate with npx tsx scripts/generate-package-validators.ts');
} else writeFileSync(path,output);
console.log('Static package validators: manifest, lists, words, questions, answers');
